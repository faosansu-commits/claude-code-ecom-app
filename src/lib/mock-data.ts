/** Derives a 4-image gallery (different crops/angles) from a single source photo. */
export function productGallery(baseImage: string): string[] {
  const [path] = baseImage.split("?")
  return galleryCrops.map((crop) => `${path}?w=1600&h=1600&q=80&auto=format&${crop}`)
}

/**
 * Picks `count` products spread across as many different categories as
 * possible (round-robin), so a "featured" grid reads as diverse rather than
 * clustered in whichever category happens to appear first in the array.
 */
export function getDiverseProducts(count: number): Product[] {
  const byCategory = new Map<number, Product[]>()
  for (const product of products) {
    const bucket = byCategory.get(product.categoryId) ?? []
    bucket.push(product)
    byCategory.set(product.categoryId, bucket)
  }
  const buckets = Array.from(byCategory.values())

  const result: Product[] = []
  for (let round = 0; result.length < count; round++) {
    const before = result.length
    for (const bucket of buckets) {
      if (round >= bucket.length) continue
      result.push(bucket[round])
      if (result.length >= count) break
    }
    if (result.length === before) break
  }
  return result
}

